const mongoose = require('mongoose');
const Workflow = require('./src/models/Workflow');
require('dotenv').config();

async function updateWorkflows() {
  try {
    await mongoose.connect(process.env.MONGODB_URI);
    const workflows = await Workflow.find({});
    let updatedCount = 0;
    
    for (let wf of workflows) {
      let modified = false;
      const newNodes = wf.nodes.map(node => {
        if (node.type === 'send_email' && node.data && node.data.htmlBody) {
          let html = node.data.htmlBody;
          
          // Replace the "les propongo estas dos opciones" text
          const oldTextRegex = /Para nuestra reuni[óoA]n inicial.*?Opciones de disponibilidad.*?Opci[óoA]n 2:.*?\[D[íi]a y Hora\]/is;
          if (html.match(oldTextRegex)) {
             html = html.replace(oldTextRegex, "(Opcional) Ya he agendado la reunión a través del botón adjunto para la siguiente fecha/hora:\\n[Pega aquí la fecha/hora de la reunión]");
             modified = true;
          }
          
          // Check if there is only 1 button and we should update it to 2 buttons
          // Actually, since these templates were GENERATED by the AI previously, 
          // they might be entirely hardcoded in the DB.
          
          node.data.htmlBody = html;
        }
        return node;
      });
      
      if (modified) {
         wf.nodes = newNodes;
         await wf.save();
         updatedCount++;
      }
    }
    
    console.log(`Updated ${updatedCount} workflows`);
  } catch(e) {
    console.error(e);
  } finally {
    mongoose.disconnect();
  }
}

updateWorkflows();
